package unievents.ui;

import javafx.beans.property.SimpleStringProperty;
import javafx.collections.FXCollections;
import javafx.geometry.Insets;
import javafx.geometry.Pos;
import javafx.scene.control.Button;
import javafx.scene.control.Label;
import javafx.scene.control.TableColumn;
import javafx.scene.control.TableView;
import javafx.scene.layout.HBox;
import javafx.scene.layout.Priority;
import javafx.scene.layout.Region;
import javafx.scene.layout.VBox;
import unievents.application.StudentController;
import unievents.domain.Notification;

import java.util.List;

/**
 * Displays in-app Notification records generated by UC2 (Registration/Waitlist),
 * UC3 (Waitlist Promotion), UC7 (Event Cancellation), and UC8 (Organizer Announcements).
 */
public class StudentNotificationsView extends VBox {
    private final StudentController controller;
    private final TableView<Notification> table = new TableView<>();
    private final Label banner = UiComponents.createBanner();

    public StudentNotificationsView(StudentController controller) {
        this.controller = controller;
        setSpacing(14);
        setPadding(new Insets(20, 24, 24, 24));
        buildView();
        refreshData();
    }

    private void buildView() {
        Label title = new Label("My Notifications");
        title.getStyleClass().add("page-title");
        Label subtitle = new Label("In-app notifications from event registrations, waitlist promotions, cancellations, and society announcements.");
        subtitle.getStyleClass().add("page-subtitle");

        TableColumn<Notification, String> colType = new TableColumn<>("Type");
        colType.setCellValueFactory(c -> new SimpleStringProperty(c.getValue().getType().name()));
        colType.setPrefWidth(145);

        TableColumn<Notification, String> colState = new TableColumn<>("State");
        colState.setCellValueFactory(c -> new SimpleStringProperty(c.getValue().isRead() ? "Read" : "NEW"));
        colState.setPrefWidth(80);

        TableColumn<Notification, String> colMsg = new TableColumn<>("Message");
        colMsg.setCellValueFactory(c -> new SimpleStringProperty(c.getValue().getMessage()));
        colMsg.setPrefWidth(540);

        TableColumn<Notification, String> colTime = new TableColumn<>("Received At");
        colTime.setCellValueFactory(c -> new SimpleStringProperty(UiComponents.formatDateTime(c.getValue().getCreatedAt())));
        colTime.setPrefWidth(170);

        table.getColumns().setAll(List.of(colType, colState, colMsg, colTime));
        table.setPlaceholder(new Label("No notifications yet."));
        VBox.setVgrow(table, Priority.ALWAYS);

        Button markReadBtn = new Button("Mark All as Read");
        markReadBtn.getStyleClass().add("btn-primary");
        markReadBtn.setOnAction(e -> {
            controller.markAllNotificationsRead();
            UiComponents.showSuccess(banner, "All notifications marked as read.");
            refreshData();
        });

        Button refreshBtn = new Button("Refresh");
        refreshBtn.getStyleClass().add("btn-secondary");
        refreshBtn.setOnAction(e -> {
            UiComponents.hideBanner(banner);
            refreshData();
        });

        Region spacer = new Region();
        HBox.setHgrow(spacer, Priority.ALWAYS);
        HBox bar = new HBox(10, markReadBtn, spacer, refreshBtn);
        bar.setAlignment(Pos.CENTER_LEFT);
        bar.getStyleClass().add("card");

        getChildren().addAll(new VBox(2, title, subtitle), banner, table, bar);
    }

    public void refreshData() {
        try {
            table.setItems(FXCollections.observableArrayList(controller.getMyNotifications()));
        } catch (RuntimeException ex) {
            UiComponents.showError(banner, ex.getMessage());
        }
    }
}
